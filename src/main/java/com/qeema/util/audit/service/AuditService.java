package com.qeema.util.audit.service;

import java.time.Instant;
import java.util.Map;
import java.util.UUID;

import org.slf4j.LoggerFactory;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.oauth2.server.resource.authentication.JwtAuthenticationToken;
import org.springframework.stereotype.Service;
import org.springframework.web.context.request.WebRequest;
import lombok.RequiredArgsConstructor;

import com.qeema.util.audit.messaging.AuditEvent;
import com.qeema.util.audit.messaging.AuditEventPublisher;
import com.qeema.util.audit.constants.AuditConstants;
import com.qeema.util.audit.utility.AuditUtility;

@Service
@RequiredArgsConstructor
public class AuditService {

        private final AuditEventPublisher producer;
        private final AuditUtility auditUtility;
        private static final org.slf4j.Logger logger = LoggerFactory.getLogger(AuditService.class);

        // I use authentication to get the actorId and username for the audit event
        // If authentication is null, I use "system" as the actorId and username this
        // may happen if the audit event is generated by a system process or a scheduled
        // task
        public void recordAuditEvent(
                        Authentication authentication,
                        String action,
                        String entityType,
                        String entityId,
                        String outcome,
                        Map<String, Object> metadata) {

                recordAuditEventWithSnapshots(authentication, action, entityType, entityId, outcome,
                                Map.of(), Map.of(), metadata);
        }

        public void recordAuditEventWithSnapshots(
                        Authentication authentication,
                        String action,
                        String entityType,
                        String entityId,
                        String outcome,
                        Map<String, Object> oldValues,
                        Map<String, Object> newValues,
                        Map<String, Object> metadata) {

                String[] actor = auditUtility.actorIds(authentication);
                String actorId = actor[0];
                String username = actor[1];

                logger.debug(
                                "Recording audit event: actorId={}, username={}, action={}, entityType={}, entityId={}, outcome={}",
                                actorId, username, action, entityType, entityId, outcome);

                producer.publish(new AuditEvent(
                                UUID.randomUUID(),
                                Instant.now(),
                                actorId,
                                username,
                                action,
                                entityType,
                                entityId,
                                outcome,
                                oldValues == null ? Map.of() : Map.copyOf(oldValues),
                                newValues == null ? Map.of() : Map.copyOf(newValues),
                                metadata == null ? Map.of() : Map.copyOf(metadata)));
        }

        public void recordRequestFailure(
                        WebRequest request,
                        int status,
                        String errorType) {
                try {
                        String path = request.getDescription(false);
                        recordAuditEventWithSnapshots(
                                        SecurityContextHolder.getContext().getAuthentication(),
                                        AuditConstants.REQUEST_FAILED,
                                        AuditConstants.HTTP_REQUEST,
                                        auditUtility.truncate(path, 100),
                                        AuditConstants.FAILURE,
                                        Map.of(),
                                        // I truncate the errorType to 100 characters to avoid exceeding the database
                                        // column length
                                        Map.of("status", status,
                                                        "errorType", auditUtility.truncate(errorType, 100)),
                                        Map.of(
                                                        "status", status,
                                                        "errorType", auditUtility.truncate(errorType, 100)));
                } catch (RuntimeException auditException) {
                        logger.warn("Unable to record request failure audit event",
                                        auditException);
                }
        }

}
